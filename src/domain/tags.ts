/**
 * Теги дня. Закрытый список: свободный ввод сделал бы статистику по тегам бессмысленной —
 * «дорога» и «в пути» считались бы разными причинами. Сна здесь нет: он спрашивается утром
 * шкалой (решение Georgy от 21.09). Новые теги — в конце (срез 5б): порядок прежних не меняется.
 */
export const DAY_TAGS = [
  'выходной',
  'дедлайн',
  'болел',
  'алкоголь',
  'дорога',
  'встречи',
  'ссора',
  'учёба',
  'отдых',
  'игры',
  'стресс',
  'работа допоздна',
] as const

/** Ступени тега с количеством (срез 5б): «выпил» и «выпил 6 порций» — разные вечера. */
export type TagLevels = {
  /** Вопрос строки в окне итога. */
  question: string
  /** Короткие подписи кнопок и чипа (индекс 0 — ступень 1). */
  short: string[]
  /** Полные подписи — шторка дня, лесенка, «Случаи». */
  long: string[]
  /** Подпись под кнопками — чтобы «много» значило одно и то же в разные дни. */
  note?: string
}

/**
 * Теги с количеством — четыре (решение Georgy 25.09, свод аналитики §3.8). Ступень необязательна: тег без неё —
 * «было, сколько — не указано», задним числом её не выдумываем. Границы алкоголя — по исследованию дозы и сна
 * (1 порция ≈ 10 г спирта).
 */
export const LEVELS: Record<string, TagLevels> = {
  'алкоголь': {
    question: 'Алкоголь — сколько?',
    short: ['1–2', '3–5', '6+'],
    long: ['1–2 порции', '3–5 порций', '6+ порций'],
    note: '1 порция ≈ бокал вина 100 мл, 0,25 л пива или рюмка 30 мл крепкого',
  },
  'игры': {
    question: 'Игры — сколько часов?',
    short: ['<1 ч', '1–2 ч', '3–4 ч', '5+ ч'],
    long: ['<1 ч', '1–2 ч', '3–4 ч', '5+ ч'],
  },
  'стресс': {
    question: 'Стресс — насколько?',
    short: ['немного', 'сильно', 'очень'],
    long: ['немного', 'сильно', 'очень сильно'],
  },
  'работа допоздна': {
    question: 'Работа допоздна — сколько сверх обычного?',
    short: ['до 1 ч', '1–3 ч', '3+ ч'],
    long: ['до 1 ч', '1–3 ч', '3+ ч'],
  },
}

/** Подпись ступени: `levelLabel('алкоголь', 2)` — «3–5», с `'long'` — «3–5 порций». Нет такой ступени — null. */
export function levelLabel(tag: string, level: number | undefined, form: 'short' | 'long' = 'short'): string | null {
  const t = LEVELS[tag]
  if (!t || level === undefined || !Number.isInteger(level) || level < 1 || level > t.short.length) return null
  return t[form][level - 1]!
}

/** Ступени, пригодные для записи: только теги из LEVELS, только отмеченные, целое 1…число ступеней. Нет ступеней — годится. */
export function validLevels(tags: string[], levels: Record<string, number> | undefined): boolean {
  if (!levels) return true
  return Object.entries(levels).every(
    ([tag, level]) => tags.includes(tag) && LEVELS[tag] !== undefined && levelLabel(tag, level) !== null,
  )
}
